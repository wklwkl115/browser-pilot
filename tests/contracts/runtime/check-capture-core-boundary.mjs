import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const read = (rel) => readFileSync(path.join(root, rel), "utf8");

const captureSrc = path.join(root, "capture-src");
const generated = path.join(root, "src", "capture", "generated");
assert(existsSync(captureSrc), "capture-src/ must own page-world sensing sources");
assert(existsSync(generated), "src/capture/generated/ must contain committed capture outputs");

const generatedFiles = readdirSync(generated).filter((name) => name.endsWith("Bundle.ts")).sort();
assert.deepEqual(generatedFiles, ["contentBundle.ts", "pickBundle.ts", "scanBundle.ts", "visionBundle.ts"], "capture generated bundle set must stay explicit");

// esbuild-migration TRIGGER (docs/capture-core-plan.md as-built deviation note): the parameterized
// string-template mechanism is accepted while there are 4 entries. Adding a 5th capture entry is one
// of the two triggers to reconsider the original real-TS + esbuild design. Pinning the source-entry
// set here makes that trigger fire as a gate failure — so the decision is made deliberately, not by
// silently growing the string mechanism. Update this list ONLY together with that reconsideration.
const entryFiles = readdirSync(path.join(root, "capture-src", "entries")).filter((name) => name.endsWith("Template.ts")).sort();
assert.deepEqual(entryFiles, ["contentTemplate.ts", "pickTemplate.ts", "scanTemplate.ts", "visionTemplate.ts"], "capture-src entry set is fixed at 4; a 5th entry triggers the esbuild-migration reconsideration (docs/capture-core-plan.md as-built note)");
for (const file of generatedFiles) {
	const text = read(`src/capture/generated/${file}`);
	assert(text.includes("Generated by scripts/sync-capture.mjs"), `${file} must be generated by sync:capture`);
	assert(/capture-sha256:[a-f0-9]{16}/.test(text), `${file} must carry deterministic source hash`);
}

const thinEntrypoints = [
	"src/scan/buildScanScript.ts",
	"src/content/buildContentScript.ts",
	"src/pick/buildPickScript.ts",
	"src/abml/verbs/visionRuntime.ts",
];
for (const rel of thinEntrypoints) {
	const text = read(rel);
	assert(text.includes("renderCaptureTemplate"), `${rel} must inject capture generated templates through the common seam`);
}

for (const rel of ["src/scan/buildScanScript.ts", "src/content/buildContentScript.ts", "src/pick/buildPickScript.ts"]) {
	const text = read(rel);
	assert(!text.includes("return String.raw`"), `${rel} must not re-own page-world template literals`);
}

const runtime = read("src/abml/verbs/runtime.ts");
for (const forbidden of ["new MutationObserver", "document.querySelector", "scrollIntoView({", "new InputEvent", "window.scrollY"]) {
	assert(!runtime.includes(forbidden), `src/abml/verbs/runtime.ts must not re-own probe page logic: ${forbidden}`);
}
const vision = read("src/abml/verbs/visionRuntime.ts");
assert(!vision.includes("document.querySelector(selector)"), "visionRuntime must not re-own viewport page logic");

const pick = read("src/capture/generated/pickBundle.ts");
const scan = read("src/capture/generated/scanBundle.ts");
for (const marker of ["if (el.id) return '#' + cssEscape(el.id)", "siblingSelectorInfo(parent", "parts.length < 6"]) {
	assert(pick.includes(marker), `pick bundle must use scan-canonical selector marker: ${marker}`);
	assert(scan.includes(marker), `scan bundle must retain canonical selector marker: ${marker}`);
}
assert(!pick.includes("Array.from(parent.children).filter"), "pick selector must not restore O(S²) sibling scans");
assert(!scan.includes("Array.from(parent.children).filter"), "scan selector must not restore O(S²) sibling scans");

console.log("capture-core boundary ok");
