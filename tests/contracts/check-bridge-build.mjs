function eventStore() {
	const listeners = [];
	return {
		listeners,
		addListener(callback) { listeners.push(callback); },
		removeListener(callback) {
			const index = listeners.indexOf(callback);
			if (index >= 0) listeners.splice(index, 1);
		},
	};
}

