import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

// Generates the parameter-doctrine reference (architecture-charter.md 铁律 #16) from the live
// command manifest. The single source of truth is the schema: `browser-pilot commands --json`
// already tags every flag `paramClass: "intent" | "mechanical"`, so this script only renders the
// decide/plumbing split — it never re-derives the classification.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const target = path.join(root, "docs", "generated", "tool-parameter-doctrine.generated.md");

function cliCommandsJson() {
	const result = spawnSync(process.execPath, [path.join(root, "node_modules", "tsx", "dist", "cli.mjs"), "cli/bin.ts", "commands", "--json"], {
		cwd: root,
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
	});
	if (result.status !== 0) {
		throw new Error(`browser-pilot commands --json failed\n${String(result.stdout || "").slice(-2000)}\n${String(result.stderr || "").slice(-2000)}`);
	}
	const text = String(result.stdout || "").trim();
	const start = text.indexOf("{");
	if (start < 0) throw new Error("browser-pilot commands --json must emit JSON");
	return JSON.parse(text.slice(start));
}

function escapeCell(value) {
	return String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function flagList(flags, paramClass) {
	const names = flags
		.filter((flag) => (flag.paramClass ?? "intent") === paramClass)
		.map((flag) => flag.flag || `--${flag.name}`)
		.sort();
	return names.length ? names.map((name) => `\`${name}\``).join(", ") : "—";
}

function render(snapshot) {
	const commands = Array.isArray(snapshot.commands) ? [...snapshot.commands].sort((a, b) => String(a.name).localeCompare(String(b.name))) : [];
	const rows = commands.map((cmd) => {
		const flags = Array.isArray(cmd.flags) ? cmd.flags : [];
		return `| \`${escapeCell(cmd.commandName || cmd.name)}\` | ${escapeCell(cmd.group || "")} | ${flagList(flags, "intent")} | ${flagList(flags, "mechanical")} |`;
	});
	return [
		"# Tool Parameter Doctrine (Generated)",
		"",
		"Generated by `scripts/sync-tool-reference.mjs` from `browser-pilot commands --json`. Do not edit by hand; run `npm run docs:sync`.",
		"",
		"Per [architecture-charter.md](../architecture-charter.md) 铁律 #16, every `browser_*` flag is either **intent** (an agent strategy choice) or **mechanical** routing (zero-strategy plumbing that carries a default — usually omit it). The single source of truth is the schema: `browser-pilot schema <cmd> --json` tags each flag `paramClass`, and CLI help groups mechanical flags under \"Plumbing (optional; defaults apply — usually omit)\". This table is the rendered snapshot of that split.",
		"",
		"| Tool | Group | Intent flags (decide) | Plumbing flags (omit unless disambiguating) |",
		"| --- | --- | --- | --- |",
		...rows,
		"",
	].join("\n");
}

const next = render(cliCommandsJson());
if (checkOnly) {
	const current = existsSync(target) ? readFileSync(target, "utf8") : "";
	if (current !== next) {
		console.error(`tool parameter doctrine doc is stale: ${path.relative(root, target)}. Run npm run docs:sync.`);
		process.exit(1);
	}
	console.log("tool parameter doctrine doc ok");
} else {
	mkdirSync(path.dirname(target), { recursive: true });
	writeFileSync(target, next, "utf8");
	console.log(`synced ${path.relative(root, target)}`);
}
