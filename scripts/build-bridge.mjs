import { build } from "esbuild";
import { mkdir, rm, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const quiet = process.argv.includes("--quiet");
const distDir = path.join(root, "bridge", "pi_browser_bridge", "dist");
const serviceWorkerBuildMode = "ordered-concat-compat";
const targetServiceWorkerBuildMode = "esm-import-graph";
const serviceWorkerModules = [
	"config", "protocol", "patterns", "cdp", "runtime", "wait_cdp", "wait_coordinator", "wait_navigation", "wait_network_idle", "wait_selector", "wait", "network_model", "network", "hook", "evidence", "frame", "html", "screenshot", "transfer", "bridge_info", "core_commands", "exec", "router", "tab_sync", "transport",
];
const entries = [
	{
		name: "service-worker",
		source: "bridge_src/service-worker.ts",
		outfile: "bridge/pi_browser_bridge/dist/service-worker.js",
	},
	{
		name: "content",
		source: "bridge_src/page_scripts/content.ts",
		outfile: "bridge/pi_browser_bridge/dist/content.js",
	},
	{
		name: "hook-dispatcher",
		source: "bridge_src/page_scripts/hook_dispatcher.ts",
		outfile: "bridge/pi_browser_bridge/dist/hook_dispatcher.js",
	},
	{
		name: "disable-dialogs",
		source: "bridge_src/page_scripts/disable_dialogs.ts",
		outfile: "bridge/pi_browser_bridge/dist/disable_dialogs.js",
	},
];
const pageScriptEntries = entries.filter((entry) => entry.name !== "service-worker");

async function serviceWorkerSource() {
	const parts = [
		"// Generated from bridge_src/service_worker/*.ts by scripts/build-bridge.mjs.",
		"// Runtime source order follows the pre-ESM bootstrap order recorded in serviceWorkerModules.",
	];
	for (const name of serviceWorkerModules) {
		const rel = `bridge_src/service_worker/${name}.ts`;
		let text = await readFile(path.join(root, rel), "utf8");
		text = text.replace(/^\/\/ @ts-nocheck\r?\n/, "").replace(/^\/\/ @ts-check\r?\n/gm, "");
		parts.push(`\n// ---- ${rel} ----\n${text.trim()}\n`);
	}
	parts.push(`
// ---- bridge_src/shared/buildInfo.ts marker ----
const BRIDGE_BUILD_PIPELINE_VERSION = "bridge-build-dist-v1";
const buildInfo = Object.freeze({ version: BRIDGE_BUILD_PIPELINE_VERSION, mode: "production", runtimeSwitched: true });
Object.defineProperty(globalThis, "__PI_BROWSER_EXPERIMENTAL_BUILD__", {
  value: buildInfo,
  configurable: false,
  enumerable: false,
  writable: false,
});
export { buildInfo };
`);
	return parts.join("\n");
}

await rm(distDir, { recursive: true, force: true });
await mkdir(distDir, { recursive: true });
await writeFile(path.join(distDir, ".gitignore"), "*\n!.gitignore\n", "utf8");
await writeFile(path.join(distDir, ".npmignore"), "# Generated by scripts/build-bridge.mjs.\n# Keep this file empty of ignore patterns so npm packages include the generated dist runtime.\n", "utf8");

const serviceWorkerEntry = entries[0];
await build({
	stdin: {
		contents: await serviceWorkerSource(),
		resolveDir: root,
		sourcefile: "bridge_src/.generated/service-worker.generated.ts",
		loader: "ts",
	},
	outfile: path.join(root, serviceWorkerEntry.outfile),
	bundle: true,
	format: "esm",
	platform: "browser",
	target: ["chrome120"],
	sourcemap: true,
	legalComments: "none",
	treeShaking: false,
	banner: { js: "// Generated by scripts/build-bridge.mjs. Do not edit by hand." },
});

for (const entry of pageScriptEntries) {
	await build({
		entryPoints: [path.join(root, entry.source)],
		outfile: path.join(root, entry.outfile),
		bundle: true,
		format: "iife",
		platform: "browser",
		target: ["chrome120"],
		sourcemap: true,
		legalComments: "none",
		treeShaking: false,
		banner: { js: "// Generated by scripts/build-bridge.mjs. Do not edit by hand." },
	});
}

await writeFile(path.join(distDir, "build-manifest.json"), JSON.stringify({
	generated: true,
	generatedBy: "scripts/build-bridge.mjs",
	runtimeSwitched: true,
	manifestTarget: "dist/service-worker.js",
	serviceWorkerBuildMode,
	targetServiceWorkerBuildMode,
	orderedConcatenation: true,
	entries,
	serviceWorkerModules,
	pageScriptEntries,
}, null, 2) + "\n", "utf8");

if (!quiet) console.log(JSON.stringify({ ok: true, distDir: path.relative(root, distDir), entries: entries.map((entry) => entry.outfile) }, null, 2));
