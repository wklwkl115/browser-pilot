import { build } from "esbuild";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(root, "bridge", "pi_browser_bridge", "dist");
const entries = [
	{
		name: "service-worker",
		source: "bridge_src/service-worker.ts",
		outfile: "bridge/pi_browser_bridge/dist/service-worker.js",
	},
];

await rm(distDir, { recursive: true, force: true });
await mkdir(distDir, { recursive: true });
await writeFile(path.join(distDir, ".gitignore"), "*\n!.gitignore\n", "utf8");

for (const entry of entries) {
	await build({
		entryPoints: [path.join(root, entry.source)],
		outfile: path.join(root, entry.outfile),
		bundle: true,
		format: "esm",
		platform: "browser",
		target: ["chrome120"],
		sourcemap: true,
		legalComments: "none",
		banner: { js: "// Generated by scripts/build-bridge.mjs. Do not edit by hand." },
	});
}

await writeFile(path.join(distDir, "build-manifest.json"), JSON.stringify({
	generated: true,
	generatedBy: "scripts/build-bridge.mjs",
	runtimeSwitched: false,
	manifestTarget: "background.js",
	entries,
}, null, 2) + "\n", "utf8");

console.log(JSON.stringify({ ok: true, distDir: path.relative(root, distDir), entries: entries.map((entry) => entry.outfile) }, null, 2));
